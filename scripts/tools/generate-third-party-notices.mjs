import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import process from 'node:process';

const root = process.cwd();
const checkOnly = process.argv.includes('--check');
const lockPath = path.join(root, 'package-lock.json');
const outputPath = path.join(root, 'THIRD_PARTY_NOTICES.md');

function normalizeText(value) {
  return String(value || '').replace(/^\uFEFF/, '').replace(/\r\n?/g, '\n').trim() + '\n';
}

function findLicenseText(packageDirectory) {
  const entries = fs.readdirSync(packageDirectory, { withFileTypes: true })
    .filter(entry => entry.isFile())
    .map(entry => entry.name);
  const preferred = entries
    .filter(name => /^(?:license|licence|copying|notice)(?:\.|$)/i.test(name))
    .sort((left, right) => left.localeCompare(right, 'en'));
  if (preferred.length) {
    const fileName = preferred[0];
    return { fileName, text: normalizeText(fs.readFileSync(path.join(packageDirectory, fileName), 'utf8')) };
  }

  const readmeName = entries.find(name => /^readme(?:\.|$)/i.test(name));
  if (readmeName) {
    const readme = normalizeText(fs.readFileSync(path.join(packageDirectory, readmeName), 'utf8'));
    const section = readme.match(/(?:^|\n)#{1,3}\s+licen[cs]e\s*\n([\s\S]+)$/i);
    if (section?.[1]) return { fileName: readmeName + '#license', text: normalizeText(section[1]) };
  }
  return null;
}

function escapeTable(value) {
  return String(value || '').replaceAll('|', '\\|').replace(/\s+/g, ' ').trim();
}

function loadLockedPackages() {
  const lock = JSON.parse(fs.readFileSync(lockPath, 'utf8'));
  return Object.entries(lock.packages || {})
    .filter(([packagePath, metadata]) => packagePath && metadata)
    .map(([packagePath, metadata]) => {
      const packageDirectory = path.join(root, packagePath);
      const installed = fs.existsSync(packageDirectory);
      const packageJson = installed
        ? JSON.parse(fs.readFileSync(path.join(packageDirectory, 'package.json'), 'utf8'))
        : {};
      const packageName = String(packageJson.name || packagePath.replace(/^node_modules[\\/]/, '').replaceAll('\\', '/'));
      const license = String(metadata.license || packageJson.license || '').trim();
      if (!license) throw new Error(`依赖没有声明许可证：${packagePath}`);

      let licenseDirectory = packageDirectory;
      let licenseSource = installed ? findLicenseText(packageDirectory) : null;
      if (!licenseSource && packageName.startsWith('@esbuild/')) {
        licenseDirectory = path.join(root, 'node_modules', 'esbuild');
        if (fs.existsSync(licenseDirectory)) licenseSource = findLicenseText(licenseDirectory);
      }
      if (!licenseSource) {
        const reason = installed ? '依赖没有可随包保留的许可证正文' : '可选依赖未安装且没有可验证的共享许可证正文';
        throw new Error(`${reason}：${packagePath}`);
      }
      const sourcePrefix = path.relative(root, licenseDirectory).replaceAll('\\', '/');
      return {
        name: packageName,
        version: String(metadata.version || packageJson.version || ''),
        license,
        usage: metadata.dev === true ? 'Build' : 'Runtime',
        licenseFile: `${sourcePrefix}/${licenseSource.fileName}`,
        licenseText: licenseSource.text
      };
    })
    .sort((left, right) => left.name.localeCompare(right.name, 'en'));
}

function render(packages) {
  const groups = new Map();
  packages.forEach(item => {
    const hash = crypto.createHash('sha256').update(item.licenseText).digest('hex');
    if (!groups.has(hash)) groups.set(hash, { text: item.licenseText, packages: [] });
    groups.get(hash).packages.push(item);
  });

  const lines = [
    '# Third-Party Notices',
    '',
    '> Generated by `npm run licenses:generate` from the complete locked dependency graph in `package-lock.json`, including runtime, build, transitive and optional platform packages. Do not remove upstream copyright or permission notices.',
    '',
    'The Omniisle Write project license does not replace the licenses below. Each dependency remains governed by its own terms.',
    '',
    '## Locked dependency inventory',
    '',
    '| Package | Version | Use | Declared license | Preserved source |',
    '| --- | --- | --- | --- | --- |'
  ];
  packages.forEach(item => {
    lines.push(`| ${escapeTable(item.name)} | ${escapeTable(item.version)} | ${escapeTable(item.usage)} | ${escapeTable(item.license)} | ${escapeTable(item.licenseFile)} |`);
  });
  lines.push('', '## Preserved license and attribution texts', '');
  [...groups.values()].forEach((group, index) => {
    lines.push(`### Notice group ${index + 1}`, '');
    lines.push('Packages: ' + group.packages.map(item => `${item.name}@${item.version}`).join(', '), '');
    lines.push('```text', group.text.trimEnd(), '```', '');
  });
  lines.push(
    '## Additional adapted source',
    '',
    '- Google LangExtract-derived chunking logic is documented in `docs/full-analysis-open-source-notices.md` and licensed under Apache-2.0. The full text is in `docs/licenses/Apache-2.0.txt`.',
    ''
  );
  return lines.join('\n');
}

const requiredFiles = [
  'docs/licenses/Apache-2.0.txt',
  'docs/full-analysis-open-source-notices.md',
  'scripts/core/app-import-full-analysis-langextract-chunker.js'
];
requiredFiles.forEach(relativePath => {
  if (!fs.existsSync(path.join(root, relativePath))) throw new Error(`缺少许可证文件：${relativePath}`);
});

const langExtractSource = fs.readFileSync(path.join(root, requiredFiles[2]), 'utf8');
if (!langExtractSource.includes('Copyright 2025 Google LLC.') || !langExtractSource.includes('SPDX-License-Identifier: Apache-2.0')) {
  throw new Error('LangExtract 衍生文件缺少 Google 归属或 Apache-2.0 标识');
}
for (const buildScript of ['scripts/tools/build-editor-runtime.mjs', 'scripts/tools/build-community-runtime.mjs']) {
  const source = fs.readFileSync(path.join(root, buildScript), 'utf8');
  if (/legalComments:\s*['"]none['"]/.test(source)) throw new Error(`${buildScript} 仍会删除许可证注释`);
}

const generated = render(loadLockedPackages());
if (checkOnly) {
  if (!fs.existsSync(outputPath) || normalizeText(fs.readFileSync(outputPath, 'utf8')) !== normalizeText(generated)) {
    throw new Error('THIRD_PARTY_NOTICES.md 不是当前依赖锁文件生成的版本，请运行 npm run licenses:generate');
  }
  console.log('[licenses] PASS 第三方依赖清单、许可证正文和 LangExtract 归属均已校验');
} else {
  fs.writeFileSync(outputPath, generated, 'utf8');
  console.log(`[licenses] 已生成 ${path.relative(root, outputPath)}`);
}
